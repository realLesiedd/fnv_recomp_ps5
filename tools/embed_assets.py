#!/usr/bin/env python3
"""Embeds the app's own assets (assets/, e.g. the button prompts from make_glyphs.py) into the executable as C data,
so the PS5 app needs nothing beyond eboot.bin. At start-up the runtime writes them to <user>/assets and lays that
folder over the game folder (rt/overlay.c).

Usage: embed_assets.py ASSETS_DIR OUT.c"""
import os, sys

src, out = sys.argv[1], sys.argv[2]
files = []
for root, _, names in os.walk(src):
    for n in sorted(names):
        full = os.path.join(root, n)
        files.append((os.path.relpath(full, src).replace(os.sep, '/'), open(full, 'rb').read()))
files.sort()
lines = ['/* generated by tools/embed_assets.py from assets/ - do not edit */', '#include <stddef.h>',
         'typedef struct { const char *path; const unsigned char *data; size_t size; } EmbeddedAsset;']
for i, (_, data) in enumerate(files):
    lines.append('static const unsigned char a%d[%d] = {' % (i, max(1, len(data))))
    for k in range(0, len(data), 24):
        lines.append(','.join(str(b) for b in data[k:k + 24]) + ',')
    lines.append('};')
lines.append('const EmbeddedAsset g_assets[] = {')
for i, (path, data) in enumerate(files):
    lines.append('  {"%s", a%d, %d},' % (path, i, len(data)))
lines.append('};')
lines.append('const int g_nassets = %d;' % len(files))
tmp = out + '.tmp'
open(tmp, 'w').write('\n'.join(lines) + '\n')
if not os.path.exists(out) or open(out).read() != open(tmp).read():
    os.replace(tmp, out)
else:
    os.remove(tmp)
